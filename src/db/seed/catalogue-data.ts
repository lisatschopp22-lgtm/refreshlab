import type { SpecField } from "@/db/schema/catalogue";
import type { Localized } from "@/db/schema/common";

/*
 * The structure follows what the large laboratory suppliers in Switzerland
 * and Germany show their customers (Carl Roth, VWR, Faust, TH.GEYER), read as
 * orientation in October 2026 and arranged into one taxonomy of our own.
 * Names of categories and manufacturers are facts; no descriptions, images or
 * product data were taken over.
 */

export type SubcategorySeed = { slug: string; name: Localized };

export type CategorySeed = {
  slug: string;
  name: Localized;
  intro: Localized;
  icon: string;
  specs: SpecField[];
  /** Device types. Each inherits the parent's spec fields. */
  children: SubcategorySeed[];
};

/** Consumables are a taxonomy only: nothing can be listed under them yet. */
export type ConsumableCategorySeed = { slug: string; name: Localized; children: SubcategorySeed[] };

const n = (key: string, de: string, en: string, unit?: string, facet = false): SpecField => ({
  key,
  label: { de, en },
  type: "number",
  unit,
  facet,
});
const t = (key: string, de: string, en: string, facet = false): SpecField => ({
  key,
  label: { de, en },
  type: "text",
  facet,
});
const sub = (slug: string, de: string, en: string): SubcategorySeed => ({ slug, name: { de, en } });

